static int tile_of(u8 c) {
    switch (c) {
        case 'P': return T_PATH;
        case '~': return T_WATER;
        case '#': return T_WALL;
        case 'r': return T_PILLAR;
        case 'T': return T_TREE;
        case 'G': return T_GATE;
        default:  return T_GRASS;
    }
}

static u8 tiles[MAP_H][MAP_W];

void map_init(void) {
    for (int y = 0; y < MAP_H; y++)
        for (int x = 0; x < MAP_W; x++)
            tiles[y][x] = (u8)tile_of(MAP[y][x]);
}

int map_tile_at(fx x, fx z) {
    int tx = (int)x >> 17;   /* world units: tile = 2.0 -> fx 131072 */
    int tz = (int)z >> 17;
    if ((u32)tx >= MAP_W || (u32)tz >= MAP_H) return -1;
    return tiles[tz][tx];
}

int map_blocked(fx x, fx z) {
    int t = map_tile_at(x, z);
    if (t < 0) return 1;
    if (t == T_WATER || t == T_WALL || t == T_TREE || t == T_PILLAR) return 1;
    if (t == T_GATE && G.quest < Q_GATE_OPEN) return 1;
    return 0;
}

int map_find(u8 ch, int* tx, int* tz) {
    for (int y = 0; y < MAP_H; y++)
        for (int x = 0; x < MAP_W; x++)
            if (MAP[y][x] == ch) { *tx = x; *tz = y; return 1; }
    return 0;
}
